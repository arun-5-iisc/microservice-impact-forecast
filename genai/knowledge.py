"""
Retrieval for the agent (RAG): past incidents in a Chroma vector database and runbooks.

Documents. One post-incident summary per training run: what the change was, what was visible
30 s after it and near the end of the fault, and the final severity. The visible signals are
generated by observation_summary() from the same replayed telemetry the agent's tools return,
so documents and the agent's view of a new incident use the same vocabulary. Holdout runs are
never indexed, and the setting of the run under investigation is filtered out at query time.

Search modes:
  keyword - TF-IDF over the summary text (scikit-learn)
  vector  - Chroma, cosine similarity of local MiniLM-L6-v2 embeddings (ONNX, CPU, no API)
  hybrid  - reciprocal-rank fusion of the two lists

Build the index once (reads every training run's traces, ~10-15 min):
  venv/bin/python -m genai.knowledge build
The index lives in models/rag_index/ (incidents.jsonl + chroma/).
"""
from __future__ import annotations

import json
import sys
import time
from collections import Counter
from functools import lru_cache
from pathlib import Path

import numpy as np
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from genai.replay import PROCESSED_DIR, SERVICES, RecordedRun, ReplayView, holdout_ids  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parent.parent
RUNBOOK_DIR = Path(__file__).resolve().parent / "knowledge" / "runbooks"
INDEX_DIR = REPO_ROOT / "models" / "rag_index"
DOCS_PATH = INDEX_DIR / "incidents.jsonl"
CHROMA_DIR = INDEX_DIR / "chroma"
COLLECTION = "past_incidents"
EARLY_T, LATE_T = 30, 170          # seconds after the change described in each document
RRF_K = 60                         # reciprocal-rank-fusion constant
SEARCH_MODES = ("keyword", "vector", "hybrid")


def setting_of(service: str, fault_type: str, fault_value, traffic_level: str) -> str:
    return f"{service}|{fault_type}|{fault_value}|{traffic_level}"


def change_text(fault_type: str, value) -> str:
    return {
        "cpu": f"CPU limit set to {value}",
        "memory": f"memory limit set to {value}",
        "latency": f"{value} ms of network latency added",
        "replicas": f"scaled to {value} replicas",
    }.get(fault_type, f"{fault_type} {value}")


# what an operator could see at a moment (shared by documents and queries)

def observation_summary(view: ReplayView, window_s: float = 30) -> str:
    svc = view.run.changed_service
    parts = []
    m = view.metrics(svc)
    before = [x for x in m if x["t"] <= 0]
    cur = m[-1] if m else None
    if cur:
        parts.append(f"replicas {cur['replicas']}")
        if cur["restarts"]:
            parts.append(f"pod restarted {cur['restarts']} time(s)")
        for key, label in (("cpu_millicores", "CPU"), ("memory_mib", "memory")):
            base = [x[key] for x in before if x[key] is not None]
            if base and np.mean(base) > 0 and cur[key] is not None:
                parts.append(f"{label} {100 * (cur[key] / np.mean(base) - 1):+.0f}%")
    reasons = Counter(e["reason"] for e in view.events(svc) if e["t_first"] > 0)
    if reasons:
        parts.append("events: " + ", ".join(f"{r} x{n}" if n > 1 else r for r, n in reasons.most_common()))

    lat = view.latency(svc, window_s)
    recent = lat.get(f"last_{int(window_s)}s", {})
    if lat.get("source") is None:
        parts.append("latency not measured")
    elif recent.get("requests", 0) == 0:
        parts.append("no requests served")
    elif "p50_change_pct" in lat:
        parts.append(f"latency p50 {lat['p50_change_pct']:+.0f}%")
    else:
        parts.append(f"latency p50 {lat['baseline'].get('p50_ms')} ms -> {recent.get('p50_ms')} ms (few requests)")
    if recent.get("error_rate", 0) >= 0.01:
        parts.append(f"error rate {100 * recent['error_rate']:.0f}%")

    slower, failing = [], []
    for s in SERVICES:
        if s == svc:
            continue
        other = view.latency(s, window_s)   # the same tests as the blast-radius label
        if other.get("significantly_slower"):
            slower.append(s)
        if other.get("significantly_more_errors"):
            failing.append(s)
    parts.append("other services slower: " + ", ".join(slower) if slower else "no other service measurably slower")
    if failing:
        parts.append("other services with errors: " + ", ".join(failing))
    return "; ".join(parts)


def incident_query(view: ReplayView) -> str:
    """What is known about a new incident at `view.now`: no cause, no outcome."""
    r = view.run
    return (f"Change to {r.changed_service} ({r.traffic_level} traffic). "
            f"At {int(round(view.now - r.change_time))} s: {observation_summary(view)}.")


def incident_document(run: RecordedRun, severity: str) -> dict:
    late_t = min(LATE_T, run.fault_end - run.change_time - 1)
    m = run._meta
    text = (f"Change to {run.changed_service} ({run.traffic_level} traffic): {change_text(m['fault_type'], m['fault_value'])}. "
            f"At {EARLY_T} s: {observation_summary(run.at(EARLY_T))}. "
            f"At {int(late_t)} s: {observation_summary(run.at(late_t))}. "
            f"Outcome: {severity} severity.")
    return {"incident_id": run.experiment_id, "service": run.changed_service, "fault_type": m["fault_type"],
            "fault_value": str(m["fault_value"]), "traffic_level": run.traffic_level,
            "setting": setting_of(run.changed_service, m["fault_type"], m["fault_value"], run.traffic_level),
            "change": change_text(m["fault_type"], m["fault_value"]), "final_severity": severity, "summary": text}


@lru_cache(maxsize=1)
def _open_collection():
    return _chroma_collection()


def _chroma_collection(create: bool = False):
    import chromadb
    from chromadb.config import Settings
    from chromadb.utils.embedding_functions import DefaultEmbeddingFunction
    client = chromadb.PersistentClient(path=str(CHROMA_DIR), settings=Settings(anonymized_telemetry=False))
    if create:
        try:
            client.delete_collection(COLLECTION)
        except Exception:
            pass
        return client.create_collection(COLLECTION, embedding_function=DefaultEmbeddingFunction(),
                                        metadata={"hnsw:space": "cosine"})
    return client.get_collection(COLLECTION, embedding_function=DefaultEmbeddingFunction())


def build_index() -> None:
    """Summarise every training run, write incidents.jsonl, and (re)create the Chroma collection."""
    import pandas as pd
    labels = (pd.read_csv(PROCESSED_DIR / "training_dataset.csv", usecols=["experiment_id", "severity"])
              .drop_duplicates("experiment_id").set_index("experiment_id")["severity"])
    holdout = set(holdout_ids())
    ids = sorted(e for e in labels.index if e not in holdout)
    INDEX_DIR.mkdir(parents=True, exist_ok=True)
    docs, t0 = [], time.time()
    for i, e in enumerate(ids, 1):
        docs.append(incident_document(RecordedRun(e), labels[e]))
        print(f"  [{i}/{len(ids)}] {e} ({time.time() - t0:.0f}s)", file=sys.stderr, flush=True)
    DOCS_PATH.write_text("".join(json.dumps(d) + "\n" for d in docs))
    col = _chroma_collection(create=True)
    meta_keys = ("incident_id", "service", "fault_type", "fault_value", "traffic_level", "setting", "final_severity")
    col.add(ids=[d["incident_id"] for d in docs], documents=[d["summary"] for d in docs],
            metadatas=[{k: d[k] for k in meta_keys} for d in docs])
    print(f"Indexed {len(docs)} incidents → {INDEX_DIR}", file=sys.stderr)


class RagIndex:
    """Search past incidents (training runs only), excluding the setting under investigation."""

    def __init__(self, exclude_setting: str | None = None):
        if not DOCS_PATH.exists():
            raise FileNotFoundError(f"{DOCS_PATH} missing — build it with: venv/bin/python -m genai.knowledge build")
        docs = [json.loads(line) for line in DOCS_PATH.read_text().splitlines()]
        self.exclude = exclude_setting
        self.docs = {d["incident_id"]: d for d in docs if d["setting"] != exclude_setting}
        self._ids = list(self.docs)
        self._tfidf = TfidfVectorizer(ngram_range=(1, 2), token_pattern=r"(?u)\b[\w.%+-]+\b")
        self._mat = self._tfidf.fit_transform([self.docs[i]["summary"] for i in self._ids])
        self._col = None    # opened lazily: keyword-only use needs no embedding model

    def _keyword(self, query: str, service: str | None) -> list[tuple[str, float]]:
        scores = cosine_similarity(self._tfidf.transform([query]), self._mat)[0]
        ranked = [(self._ids[i], float(scores[i])) for i in np.argsort(-scores)]
        return [(i, s) for i, s in ranked if not service or self.docs[i]["service"] == service]

    def _vector(self, query: str, service: str | None, n: int) -> list[tuple[str, float]]:
        if self._col is None:
            self._col = _open_collection()
        conds = ([{"setting": {"$ne": self.exclude}}] if self.exclude else []) + \
                ([{"service": service}] if service else [])
        where = conds[0] if len(conds) == 1 else ({"$and": conds} if conds else None)
        r = self._col.query(query_texts=[query], n_results=n, where=where)
        return [(i, 1 - d) for i, d in zip(r["ids"][0], r["distances"][0])]

    def search(self, query: str, service: str | None = None, k: int = 5, mode: str = "hybrid") -> list[dict]:
        k = max(1, min(k, 10))
        pool = min(50, len(self._ids))
        if mode == "keyword":
            ranked = self._keyword(query, service)[:k]
        elif mode == "vector":
            ranked = self._vector(query, service, k)
        elif mode == "hybrid":
            fused: dict[str, float] = {}
            for lst in (self._keyword(query, service)[:pool], self._vector(query, service, pool)):
                for rank, (i, _) in enumerate(lst):
                    fused[i] = fused.get(i, 0.0) + 1 / (RRF_K + rank + 1)
            ranked = sorted(fused.items(), key=lambda x: -x[1])[:k]
        else:
            raise ValueError(f"mode must be one of {SEARCH_MODES}")
        out = []
        for i, score in ranked:
            d = self.docs[i]
            out.append({"incident_id": i, "changed_service": d["service"], "change": d["change"],
                        "final_severity": d["final_severity"], "summary": d["summary"], "score": round(score, 4)})
        return out


def list_runbooks() -> list[str]:
    return sorted(p.stem for p in RUNBOOK_DIR.glob("*.md"))


def get_runbook(name: str) -> str:
    if name not in list_runbooks():
        raise ValueError(f"unknown runbook '{name}'; available: {', '.join(list_runbooks())}")
    return (RUNBOOK_DIR / f"{name}.md").read_text()


if __name__ == "__main__":
    if sys.argv[1:] == ["build"]:
        build_index()
    else:
        sys.exit("usage: python -m genai.knowledge build")
